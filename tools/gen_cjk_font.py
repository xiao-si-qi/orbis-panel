#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Generate LVGL 9 C-array font with full GB2312 + ASCII coverage.

Why: LVGL's built-in CJK fonts (simsun/source-han 16) only cover ~1200
characters, so common entity names like "摄像头" show up as boxes. This script
rasterises a system TrueType font (Microsoft YaHei by default) with Pillow and
emits a `lv_font_fmt_txt` font in the exact layout LVGL 9 expects (4bpp plain,
sparse-full cmap).

Usage:
    python tools/gen_cjk_font.py [--size 18] [--font C:/Windows/Fonts/msyh.ttc]
"""

import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

EXTRA_CHARS = "·—…“”‘’℃±×÷°①②③④⑤⑥⑦⑧⑨⑩"


def build_charset():
    cps = set(range(0x20, 0x7F))  # ASCII printable
    # GB2312 double byte area: 6763 hanzi + 682 symbols
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes((hi, lo)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            cps.add(ord(ch))
    cps.update(ord(c) for c in EXTRA_CHARS)
    return sorted(cps)


def emit_byte_array(fh, name, data, per_line=24):
    fh.write("static LV_ATTRIBUTE_LARGE_CONST const uint8_t %s[] = {\n" % name)
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        fh.write("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
    fh.write("};\n\n")


def emit_u16_array(fh, name, values, per_line=16):
    fh.write("static const uint16_t %s[] = {\n" % name)
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        fh.write("    " + ", ".join("0x%04x" % v for v in chunk) + ",\n")
    fh.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=18)
    ap.add_argument("--font", default=r"C:\Windows\Fonts\msyh.ttc")
    ap.add_argument("--index", type=int, default=0)
    ap.add_argument("--variation", default="Regular",
                    help="variable font instance name (Noto Sans SC defaults to Thin!)")
    ap.add_argument("--out-dir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "fonts"))
    ap.add_argument("--name", default=None)
    args = ap.parse_args()

    size = args.size
    name = args.name or ("lv_font_ha_%d_cjk" % size)
    out_dir = os.path.abspath(args.out_dir)
    os.makedirs(out_dir, exist_ok=True)

    font = ImageFont.truetype(args.font, size, index=args.index)
    try:
        font.set_variation_by_name(args.variation)
        print("variation: %s -> %s" % (args.variation, font.getname()))
    except Exception as exc:  # static font, or name not available
        print("variation not applied (%s)" % exc)
    ascent, descent = font.getmetrics()
    line_height = ascent + descent
    print("font=%s size=%d ascent=%d descent=%d line_height=%d" % (args.font, size, ascent, descent, line_height))

    charset = build_charset()
    print("characters: %d" % len(charset))

    bitmap = bytearray()
    glyphs = []  # (cp, bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y)
    missing = 0

    for cp in charset:
        ch = chr(cp)
        try:
            x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        except Exception:
            missing += 1
            continue

        adv_w = int(round(font.getlength(ch) * 16))
        w = x1 - x0
        h = y1 - y0

        if w <= 0 or h <= 0:
            glyphs.append((cp, len(bitmap), adv_w, 0, 0, 0, 0))
            continue

        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        px = img.load()

        start = len(bitmap)
        # LVGL unpacks 4bpp glyphs as one continuous nibble stream (no per-row
        # padding), so pack row-major across the whole glyph and only pad the
        # very last nibble to a byte boundary.
        nibbles = []
        for row in range(h):
            for col in range(w):
                nibbles.append(min(15, int((px[col, row] + 8) / 17)))
        if len(nibbles) % 2:
            nibbles.append(0)
        for i in range(0, len(nibbles), 2):
            bitmap.append(((nibbles[i] << 4) | nibbles[i + 1]) & 0xFF)

        glyphs.append((cp, start, adv_w, w, h, x0, -y1))

    print("glyphs: %d  bitmap bytes: %d  skipped: %d" % (len(glyphs), len(bitmap), missing))

    # sparse-full cmap over one range: rcp = cp - range_start, must fit in uint16
    range_start = glyphs[0][0]
    unicode_list = []
    ofs_list = []
    for idx, g in enumerate(glyphs):
        rcp = g[0] - range_start
        if rcp > 0xFFFF:
            continue
        unicode_list.append(rcp)
        ofs_list.append(idx)  # glyph_id = glyph_id_start(1) + ofs
    max_rcp = max(unicode_list)

    c_path = os.path.join(out_dir, name + ".c")
    h_path = os.path.join(out_dir, name + ".h")

    with open(h_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* Auto-generated by tools/gen_cjk_font.py - do not edit */\n")
        fh.write("#pragma once\n\n#include \"lvgl.h\"\n\n")
        fh.write("LV_FONT_DECLARE(%s);\n" % name)

    with open(c_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/*\n * Auto-generated by tools/gen_cjk_font.py\n")
        fh.write(" * Source font: %s, %dpx, GB2312 + ASCII, 4bpp\n" % (os.path.basename(args.font), size))
        fh.write(" */\n\n#include \"%s.h\"\n\n" % name)

        emit_byte_array(fh, "glyph_bitmap", bitmap)

        fh.write("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n")
        fh.write("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},\n")
        for (cp, start, adv_w, w, h, ox, oy) in glyphs:
            fh.write("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},\n"
                     % (start, adv_w, w, h, ox, oy))
        fh.write("};\n\n")

        emit_u16_array(fh, "unicode_list", unicode_list)
        emit_u16_array(fh, "glyph_id_ofs_list", ofs_list)

        fh.write("static const lv_font_fmt_txt_cmap_t cmaps[] = {\n")
        fh.write("    {\n")
        fh.write("        .range_start = 0x%04x,\n" % range_start)
        fh.write("        .range_length = 0x%04x,\n" % (max_rcp + 1))
        fh.write("        .glyph_id_start = 1,\n")
        fh.write("        .unicode_list = unicode_list,\n")
        fh.write("        .glyph_id_ofs_list = glyph_id_ofs_list,\n")
        fh.write("        .list_length = %d,\n" % len(unicode_list))
        fh.write("        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_FULL,\n")
        fh.write("    },\n};\n\n")

        fh.write("static const lv_font_fmt_txt_dsc_t font_dsc = {\n")
        fh.write("    .glyph_bitmap = glyph_bitmap,\n")
        fh.write("    .glyph_dsc = glyph_dsc,\n")
        fh.write("    .cmaps = cmaps,\n")
        fh.write("    .kern_dsc = NULL,\n")
        fh.write("    .kern_scale = 0,\n")
        fh.write("    .cmap_num = 1,\n")
        fh.write("    .bpp = 4,\n")
        fh.write("    .kern_classes = 0,\n")
        fh.write("    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,\n")
        fh.write("};\n\n")

        fh.write("const lv_font_t %s = {\n" % name)
        fh.write("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n")
        fh.write("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n")
        fh.write("    .line_height = %d,\n" % line_height)
        fh.write("    .base_line = %d,\n" % descent)
        fh.write("    .subpx = LV_FONT_SUBPX_NONE,\n")
        fh.write("    .underline_position = -2,\n")
        fh.write("    .underline_thickness = 1,\n")
        fh.write("    .dsc = &font_dsc,\n")
        fh.write("    .fallback = NULL,\n")
        fh.write("};\n")

    print("wrote %s (%d bytes)" % (c_path, os.path.getsize(c_path)))


if __name__ == "__main__":
    main()
